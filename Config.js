function buildOptionsSheet_(ss) {
  const sh = getOrCreateSheet_(ss, '系統選項');
  sh.clear();

  const data = [
    ['訂單狀態','付款狀態','派車狀態','司機狀態','啟用狀態','派遣優先','會員等級','會員狀態','派遣結果','衝突檢查','資料狀態'],
    ['待確認','未付款','未派車','可派遣','是','高','一般','啟用','待確認','通過','正常'],
    ['已確認','已付訂金','待司機確認','休假','否','中','銀卡','停用','已接受','司機衝突','需確認'],
    ['進行中','已付款','已派車','執勤中','','低','金卡','黑名單','已拒絕','車牌衝突','資料不完整'],
    ['已完成','退款中','執行中','停用','','','VIP','','已取消','資料不足','異常'],
    ['已取消','已退款','已完成','維修中','','','','','已完成','',''],
    ['No Show','','已取消','','','','','','','','']
  ];

  sh.getRange(1,1,data.length,data[0].length).setValues(data);
  styleHeader_(sh.getRange(1,1,1,data[0].length));
  sh.setFrozenRows(1);
  sh.autoResizeColumns(1, data[0].length);
  sh.hideSheet();
}
